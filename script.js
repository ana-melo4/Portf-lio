document.addEventListener('DOMContentLoaded', () => {
    
    // Inicialização do AOS
    if (typeof AOS !== 'undefined') {
        AOS.init({
            duration: 1000,
            once: true,
            offset: 100
        });
    }

    // Parallax das lanternas na Hero Section
    const hero = document.querySelector('.hero-section');
    const lanterns = document.querySelectorAll('.parallax-lantern');

    if (hero) {
        hero.addEventListener('mousemove', (e) => {
            const x = (e.clientX / window.innerWidth) - 0.5;
            const y = (e.clientY / window.innerHeight) - 0.5;
            
            lanterns.forEach((lantern, index) => {
                const speeds = [40, 60, 25, 50]; 
                const speed = speeds[index] || 30;

                const xOffset = x * speed;
                const yOffset = y * speed;
                
                lantern.style.transform = `translate(${xOffset}px, ${yOffset}px)`;
            });
        });
    }
});

// Rolagem das fotos no rodapé
function rolarCarrossel(botao, direcao) {
    const caixa = botao.closest('.caixa-carrossel');
    const trilha = caixa.querySelector('.trilha-imagens');
    const largura = trilha.clientWidth;
    trilha.scrollBy({ left: direcao * largura, behavior: 'smooth' });
}

// Funções da Seção de Matérias
function openSubjectView(subjectKey) {
    currentSubjectKey = subjectKey;
    const subjectData = subjectsData[subjectKey];

    document.getElementById('subject-title').innerText = subjectData.title;
    
    // Preenche as atividades dos 3 trimestres
    renderActivitiesForTrimester(1);
    renderActivitiesForTrimester(2);
    renderActivitiesForTrimester(3);

    // Esconde a grade de matérias e exibe o container de detalhamento
    document.getElementById('subjects-grid').style.display = 'none';
    document.getElementById('subject-detail').style.display = 'block';

    // Inicia a navegação no 1º Trimestre
    jumpToTrimester(1);
}

function closeSubjectView() {
    document.getElementById('subject-detail').style.display = 'none';
    document.getElementById('subjects-grid').style.display = 'grid';
}

function renderActivitiesForTrimester(trimesterNum) {
    const container = document.getElementById(`activities-t${trimesterNum}`);
    container.innerHTML = '';

    const list = subjectsData[currentSubjectKey].trimesters[trimesterNum] || [];

    if (list.length === 0) {
        container.innerHTML = `<p class="empty-activity">Nenhuma atividade cadastrada para este trimestre ainda.</p>`;
        return;
    }

    list.forEach(act => {
        const card = document.createElement('div');
        card.className = 'activity-card';

        let innerHTML = `<h4>${act.title}</h4>`;
        innerHTML += `<div class="scrollable-text">`;
        innerHTML += `<p>${act.desc}</p>`;

        if (act.skills && act.skills.trim() !== '') {
            innerHTML += `<h5><strong>Habilidades:</strong><br>${act.skills}</h5>`;
        }
        innerHTML += `</div>`;

        if (act.link) {
            innerHTML += `<a href="${act.link}" target="_blank" class="activity-link">Ver Atividade Completa →</a>`;
        }

        card.innerHTML = innerHTML;
        container.appendChild(card);
    });
}

function jumpToTrimester(trimesterNum) {
    currentTrimesterIndex = trimesterNum;
    
    // Atualiza botão ativo
    const tabs = document.querySelectorAll('.trimester-tab');
    tabs.forEach(tab => {
        if (parseInt(tab.getAttribute('data-trimester')) === trimesterNum) {
            tab.classList.add('active');
        } else {
            tab.classList.remove('active');
        }
    });

    // Desloca o trilho de trimestres (300% de largura total = 100% por painel)
    const track = document.getElementById('trimester-track');
    const offset = (trimesterNum - 1) * (100 / 3);
    track.style.transform = `translateX(-${offset}%)`;
}

function changeTrimester(direction) {
    let newIndex = currentTrimesterIndex + direction;
    if (newIndex < 1) newIndex = 3;
    if (newIndex > 3) newIndex = 1;
    jumpToTrimester(newIndex);
}